create table if not exists public.sales (
  id bigint generated by default as identity primary key,
  sale_date date not null,
  company text not null,
  country text not null,
  category text not null,
  product text not null,
  channel text not null,
  qty integer not null default 0,
  price numeric(14, 2) not null default 0,
  sales numeric(14, 2) not null default 0,
  profit numeric(14, 2) not null default 0,
  marketing numeric(14, 2) not null default 0,
  defect numeric(8, 4) not null default 0,
  ontime numeric(8, 4) not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists sales_sale_date_idx on public.sales (sale_date);
create index if not exists sales_category_idx on public.sales (category);
create index if not exists sales_channel_idx on public.sales (channel);
create index if not exists sales_country_idx on public.sales (country);

alter table public.sales enable row level security;

drop policy if exists "Allow public dashboard reads" on public.sales;
create policy "Allow public dashboard reads"
  on public.sales
  for select
  to anon, authenticated
  using (true);

